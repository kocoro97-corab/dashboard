'use strict';
const assert=require('node:assert/strict');
const A=require('../js/stock-setup-adapter.js');
const E=require('../js/stock-setup-engine.js');
const stamp=Date.UTC(2026,8,1);
const dates=Array.from({length:68},(_,i)=>new Date(stamp+i*86400000).toISOString().slice(0,10));
const raw=dates.map((date,i)=>{const c=100+i;return {t:stamp+i*86400000,o:c-1,h:c+1,l:c-2,c,v:1000}});
const fixture={symbol:'SERV',currency:'USD',exchange:'NMS',source:'Yahoo validated chart',
 observedAt:raw.at(-1).t,receivedAt:Date.now(),bars:raw};
const opts={symbol:'SERV',market:'US',dates,verifiedSource:true,closedDates:dates.slice(0,-1)};
const res=A.adapt(fixture,opts);
assert.equal(res.status,'ready');
assert.equal(res.excludedOpenBars,1);
assert.equal(res.bars.length,67);
assert.equal(res.bars[0].date,dates[0]);
assert.equal(res.bars.at(-1).date,dates.at(-2));
assert.equal(E.assess({symbol:'SERV',market:'US',currency:'USD',bars:res.bars,mode:'swing',verified:true,source:res.source}).status,'descriptive');
assert.equal(A.adapt(fixture,{...opts,verifiedSource:false}).status,'unavailable');
assert.equal(A.adapt(fixture,{...opts,dates:null}).status,'unavailable');
assert.equal(A.adapt(fixture,{...opts,closedDates:[]}).status,'unavailable');
assert.equal(A.adapt(fixture,{...opts,closedDates:[...dates,'2026-01-01']}).status,'unavailable');
assert.equal(A.adapt({...fixture,exchange:'KSC'},opts).status,'unavailable');
assert.equal(A.adapt({...fixture,currency:'KRW'},opts).status,'unavailable');
assert.equal(A.adapt({...fixture,symbol:'MSTY'},opts).status,'unavailable');
const bad=[...raw];bad[12]={...bad[12],h:0};
assert.equal(A.adapt({...fixture,bars:bad},opts).status,'unavailable');
const datesBad=[...dates];datesBad[8]='2026-02-30';
assert.equal(A.adapt(fixture,{...opts,dates:datesBad}).status,'unavailable');
const dateDuplicate=[...dates];dateDuplicate[8]=dateDuplicate[7];
assert.equal(A.adapt(fixture,{...opts,dates:dateDuplicate}).status,'unavailable');
const kr={...fixture,symbol:'005930',currency:'KRW',exchange:'KSC'};
assert.equal(A.adapt(kr,{...opts,symbol:'005930',market:'KR'}).status,'ready');
console.log('Stock setup adapter: verified identities, KST/US session metadata, unclosed bars, OHLCV failures PASS');
