'use strict';
const assert=require('node:assert/strict');
const E=require('../js/stock-setup-engine.js');
const days=Array.from({length:90},(_,i)=>new Date(Date.UTC(2026,7,1+i)).toISOString().slice(0,10));
function fixtures({slope=1.0,volume=1000}={}){
 return days.map((date,i)=>{
  const c=100+slope*i;
  return {date,o:c-0.8,h:c+0.5,l:c-2,c,v:volume,closed:true};
 });
}
function input(mode='swing',bars=fixtures()){
 return {symbol:'SERV',market:'US',currency:'USD',source:'Yahoo verified chart',verified:true,mode,bars,
  nowDay:bars.at(-1).date};
}
const US={region:'US',status:'descriptive',direction:{state:'up'},risk:{level:'reference-low'},momentum:{state:'strengthening'}};
const rotation={market:'US',status:'descriptive',type:'sector_etf_proxy',rotation:{status:'descriptive',relative5dPp:3.2,relative20dPp:5.1}};
const benchmark={market:'US',symbol:'SPY',verified:true,source:'Yahoo verified chart',bars:fixtures({slope:0.5})};
let x=E.assess({...input('swing'),benchmark,regime:US,sector:rotation});
assert.equal(x.status,'descriptive');
assert.equal(x.setup.trend,'up');
assert.equal(x.setup.return5dPct>0,true);
assert.equal(x.setup.return20dPct>0,true);
assert.equal(x.setup.ma60!==null,true);
assert.equal(x.relative.status,'ready');
assert.equal(x.relative.period5.status,'ready');
assert.equal(x.relative.period20.status,'ready');
assert.equal(x.relative.period5.relativePp>0,true);
assert.equal(x.marketContext.status,'observed');
assert.equal(x.sectorContext.status,'observed');
assert.equal(x.sectorContext.scope,'ETF 대용지표');
assert.equal(x.references.supportStatus,'reference-only');
assert.equal(x.warnings.some(a=>a.includes('매매 신호')),true);
assert.equal(typeof E.placeOrder,'undefined');
const day=E.assess(input('day'));
assert.equal(day.status,'descriptive');
assert.equal(day.setup.closeBreak20,true);
assert.equal(day.setup.volumeStatus,'normal');
assert.equal(day.setup.candidates.length,1);
assert.equal(day.setup.candidates[0].type,'breakout_unconfirmed_volume');
const surge=fixtures();
surge[surge.length-1]={...surge.at(-1),v:2100};
x=E.assess(input('day',surge));
assert.equal(x.setup.volumeStatus,'expanded');
assert.equal(x.setup.candidates[0].type,'breakout_volume');
const lowVolume=fixtures();
lowVolume.at(-1).v=null;
x=E.assess(input('day',lowVolume));
assert.equal(x.setup.volumeStatus,'unknown');
assert.equal(x.setup.candidates[0].type,'breakout_unconfirmed_volume');
const down=fixtures({slope:-0.5});
x=E.assess(input('swing',down));
assert.equal(x.setup.trend,'down');
assert.equal(x.setup.candidates.length,0);
const partial=fixtures().slice(-10);
x=E.assess(input('swing',partial));
assert.equal(x.status,'insufficient');
assert.equal(x.setup.ma20,null);
assert.equal(x.setup.candidates.length,0);
const invalid=fixtures();invalid.at(-1).closed=false;
assert.equal(E.assess(input('day',invalid)).status,'unavailable');
const badOHLC=fixtures();badOHLC[3].h=badOHLC[3].l-1;
assert.equal(E.assess(input('day',badOHLC)).status,'unavailable');
const duplicate=fixtures();duplicate[4].date=duplicate[3].date;
assert.equal(E.assess(input('day',duplicate)).status,'unavailable');
assert.equal(E.assess({...input(),market:'KR'}).status,'unavailable');
assert.equal(E.assess({...input(),verified:false}).status,'unavailable');
assert.equal(E.assess({...input(),currency:'KRW'}).status,'unavailable');
assert.equal(E.assess({...input(),nowDay:'2027-11-23'}).status,'unavailable');
assert.equal(E.assess({...input(),benchmark:{...benchmark,verified:false}}).relative.status,'unavailable');
const misaligned={...benchmark,bars:benchmark.bars.slice(0,-1)};
assert.equal(E.assess({...input(),benchmark:misaligned}).relative.status,'insufficient');
const gapBench={...benchmark,bars:benchmark.bars.filter((_,i)=>i!==87)};
x=E.assess({...input(),benchmark:gapBench});
assert.equal(x.relative.period5.status,'insufficient');
assert.equal(E.assess({...input(),regime:{...US,region:'KR'}}).marketContext.status,'unknown');
assert.equal(E.assess({...input(),sector:{...rotation,market:'KR'}}).sectorContext.status,'unknown');
const korea=fixtures().map(b=>({...b}));
assert.equal(E.assess({...input('day',korea),symbol:'005930',market:'KR',currency:'KRW'}).status,'descriptive');
console.log('Stock setup engine: validated day/swing setup, 20-day breakout, relative strength, risk and failure gates PASS');
